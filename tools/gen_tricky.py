EXTRA_CONTROL = {7: [("CARD", "4276 5500 1122 3347")]}

PREFIXES = ["", "Сообщение оператора: ", "Из письма: ", "Комментарий: ", "Запись в журнале: "]
SUFFIXES = ["", " Спасибо.", " Подробности в приложении.", " Просьба учесть.", " Конец записи."]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="tests/data/tricky_negatives.jsonl")
    a = ap.parse_args()
    rnd = random.Random(SEED)
    rows = []
    for tag, texts in NEGATIVES:
        for i, base in enumerate(texts):
            for k in range(3):  # same trap in three surroundings
                text = rnd.choice(PREFIXES) + base + rnd.choice(SUFFIXES)
                rows.append({"id": f"trk-{tag}-{i:02d}-{k}", "text": text, "entities": [],
                             "source": "own/tricky", "tags": ["hard-negative", tag]})
    for i, (text, type_, value) in enumerate(CONTROL):
        ents = []
        for t, v in [(type_, value)] + EXTRA_CONTROL.get(i, []):
            start = text.index(v)
            ents.append({"type": t, "start": start, "end": start + len(v), "text": v})
        rows.append({"id": f"trk-control-{i:02d}", "text": text, "entities": ents,
                     "source": "own/tricky", "tags": ["control", "positive"]})
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    neg = sum(1 for r in rows if not r["entities"])
    print(f"{a.out}: {len(rows)} rows, {neg} look-alikes, {len(rows) - neg} control rows with real PII")


if __name__ == "__main__":
    main()
